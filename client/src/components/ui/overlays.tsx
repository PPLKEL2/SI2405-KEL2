export function InfoTooltip({ text }: { text: string }) {
  return (
    <TooltipPrimitive.Root delayDuration={180}>
      <TooltipPrimitive.Trigger asChild>
        <button
          type="button"
          aria-label="Informasi tambahan"
          className="inline-flex h-6 w-6 items-center justify-center rounded-full text-mute transition hover:bg-slate-100 hover:text-ink"
        >
          <HelpCircle className="h-3.5 w-3.5" />
        </button>
      </TooltipPrimitive.Trigger>
      <TooltipPrimitive.Portal>
        <TooltipPrimitive.Content
          sideOffset={6}
          className="z-50 max-w-xs rounded-xl bg-slate-900 px-3 py-2 text-xs leading-relaxed text-white shadow-lg"
        >
          {text}
          <TooltipPrimitive.Arrow className="fill-slate-900" />
        </TooltipPrimitive.Content>
      </TooltipPrimitive.Portal>
    </TooltipPrimitive.Root>
  );
}

